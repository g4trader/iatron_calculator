import { test, expect } from '@playwright/test';
import { PrismaClient } from '@prisma/client';
import { mkdir } from 'node:fs/promises';
import { login } from './helpers/auth';
import { COMMUNITY_SETTING, COMMUNITY_PRODUCT, communityDefaults } from '../lib/mentory/community-validation';
const db = new PrismaClient();
const base = 'http://127.0.0.1:3000';
const invite = 'https://chat.whatsapp.com/TestInvitationCode12345';
const config = { ...communityDefaults, enabled: true, inviteUrl: invite, supportPhone: '15555550123' };
test.afterAll(() => db.$disconnect());
test('Comunidade: administração, persistência, concorrência, autorização e acesso revogado', async ({ page, browser, request }, info) => {
  const old = await db.appSetting.findUnique({ where: { key: COMMUNITY_SETTING } });
  const out = process.env.COMMUNITY_EVIDENCE_DIR || info.outputDir;
  await mkdir(out, { recursive: true });
  const studentContext = await browser.newContext({ baseURL: base, viewport: page.viewportSize() });
  const student = await studentContext.newPage();
  const enrollment = await db.mentoryEnrollment.findFirstOrThrow({ where: { userId: 'mentory-test-student-a' } });
  const subscription = await db.mentorySubscription.findUniqueOrThrow({ where: { id: enrollment.subscriptionId } });
  try {
    await db.appSetting.deleteMany({ where: { key: COMMUNITY_SETTING } });
    expect((await request.post('/api/mentory/community/join', { data: { accepted: true } })).status()).toBe(401);
    expect((await request.post('/api/mentory/community/settings', { data: { config, version: null } })).status()).toBe(401);
    await page.goto('/mentory/admin/comunidade'); await expect(page).toHaveURL(/mentory\/login/);
    await page.goto('/mentory/comunidade'); await expect(page).toHaveURL(/mentory\/login/);
    await login(page, 'mentory-test-admin@iatron.test', '/mentory/admin/comunidade');
    await expect(page.getByRole('heading', { name: 'Gestão da comunidade', exact: true })).toBeVisible();
    const adminPost = (body: unknown, origin = base) => page.request.post('/api/mentory/community/settings', { headers: { origin }, data: body });
    expect((await adminPost({ config, version: null }, 'https://evil.test')).status()).toBe(403);
    expect((await adminPost({ config: { ...config, inviteUrl: 'https://evil.test/invite' }, version: null })).status()).toBe(400);
    await page.getByLabel('Convite da comunidade no WhatsApp').filter({ visible: true }).fill(invite);
    await page.getByLabel('WhatsApp de suporte ao acesso (opcional)').filter({ visible: true }).fill(config.supportPhone);
    await page.getByLabel('Liberar convite para alunos com mentoria ativa').filter({ visible: true }).check();
    await page.getByRole('button', { name: 'Salvar comunidade' }).click();
    await expect(page.getByRole('status')).toContainText('Configuração da comunidade salva.');
    await page.reload(); await expect(page.getByLabel('Convite da comunidade no WhatsApp').filter({ visible: true })).toHaveValue(invite);
    expect((await adminPost({ config, version: null })).status()).toBe(409);
    const previousVersion = (await db.appSetting.findUniqueOrThrow({ where: { key: COMMUNITY_SETTING } })).updatedAt.toISOString();
    await page.getByLabel('Mensagem de boas-vindas').filter({ visible: true }).fill(config.welcome + ' Compartilhe sua jornada.');
    await page.getByRole('button', { name: 'Salvar comunidade' }).click();
    await expect(page.getByRole('status')).toContainText('Configuração da comunidade salva.');
    expect((await adminPost({ config, version: previousVersion })).status()).toBe(409);
    expect((await page.request.post('/api/mentory/community/join', { headers: { origin: base }, data: { accepted: true } })).status()).toBe(403);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: `${out}/community-admin-${info.project.name}.png`, fullPage: true });
    await login(student, 'mentory-test-student-a@iatron.test', '/mentory/comunidade');
    await expect(student.getByRole('heading', { name: 'Comunidade MENTOR.iatron' })).toBeVisible();
    expect(await student.content()).not.toContain('TestInvitationCode12345');
    await expect(student.getByRole('link', { name: 'Falar com o suporte ↗' })).toHaveAttribute('href', 'https://wa.me/' + config.supportPhone);
    const join = student.getByRole('button', { name: 'Entrar na comunidade', exact: true });
    await expect(join).toBeDisabled();
    const post = (path: string, body: unknown, origin = base) => student.request.post('/api/mentory/community/' + path, { headers: { origin }, data: body });
    expect((await post('settings', { config, version: null })).status()).toBe(403);
    expect((await post('join', { accepted: false })).status()).toBe(400);
    expect((await post('join', { accepted: true, userId: 'another' })).status()).toBe(400);
    expect((await post('join', { accepted: true }, 'https://evil.test')).status()).toBe(403);
    await student.getByRole('checkbox').check(); await expect(join).toBeEnabled();
    expect(await student.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await student.screenshot({ path: `${out}/community-student-${info.project.name}.png`, fullPage: true });
    await student.route('https://chat.whatsapp.com/**', route => route.fulfill({ contentType: 'text/html', body: '<h1>Destino WhatsApp interceptado no teste</h1>' }));
    await join.click(); await expect(student).toHaveURL(invite);
    const audit = await db.mentoryAuditLog.findFirstOrThrow({ where: { actorId: enrollment.userId, entityId: COMMUNITY_PRODUCT, action: 'community.invite.opened' }, orderBy: { timestamp: 'desc' } });
    expect(JSON.stringify(audit)).not.toContain('TestInvitationCode12345');
    expect(audit.metadata).toMatchObject({ source: 'MENTORY_BONUS' });
    await page.reload(); await expect(page.getByRole('link', { name: 'Conferir assinatura →' }).first()).toBeVisible();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: `${out}/community-audit-${info.project.name}.png`, fullPage: true });
    await student.goto('/mentory/comunidade');
    await db.mentorySubscription.update({ where: { id: subscription.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
    expect((await post('join', { accepted: true })).status()).toBe(403);
    await student.reload(); await expect(student.getByRole('link', { name: 'Consultar minha assinatura' })).toBeVisible();
    await expect(student.getByRole('button', { name: 'Entrar na comunidade' })).toHaveCount(0);
    expect(await student.content()).not.toContain('TestInvitationCode12345');
    await student.screenshot({ path: `${out}/community-expired-${info.project.name}.png`, fullPage: true });
    await db.mentorySubscription.update({ where: { id: subscription.id }, data: { expiresAt: subscription.expiresAt } });
    await db.mentoryEnrollment.update({ where: { id: enrollment.id }, data: { status: 'CANCELED' } });
    expect((await post('join', { accepted: true })).status()).toBe(403);
    await db.mentoryEnrollment.update({ where: { id: enrollment.id }, data: { status: enrollment.status } });
    await db.appSetting.update({ where: { key: COMMUNITY_SETTING }, data: { value: JSON.stringify({ ...config, enabled: false }) } });
    expect((await post('join', { accepted: true })).status()).toBe(423);
    await student.reload(); await expect(student.getByText('Convite indisponível no momento', { exact: true })).toBeVisible();
    await student.screenshot({ path: `${out}/community-paused-${info.project.name}.png`, fullPage: true });
    await db.userSession.updateMany({ where: { userId: enrollment.userId, status: 'ACTIVE' }, data: { status: 'REVOKED', revokedAt: new Date() } });
    expect((await post('join', { accepted: true })).status()).toBe(401);
    await login(page, 'mentory-test-editor@iatron.test', '/mentory/admin/comunidade');
    await expect(page).toHaveURL(/\/mentory\/admin$/);
    expect((await adminPost({ config, version: null })).status()).toBe(403);
  } finally {
    await db.mentoryEnrollment.update({ where: { id: enrollment.id }, data: { status: enrollment.status } });
    await db.mentorySubscription.update({ where: { id: subscription.id }, data: { expiresAt: subscription.expiresAt } });
    await db.appSetting.deleteMany({ where: { key: COMMUNITY_SETTING } });
    if (old) await db.appSetting.create({ data: old });
    await studentContext.close();
  }
});
